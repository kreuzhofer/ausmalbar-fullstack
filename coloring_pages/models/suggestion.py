"""
Model for persisting AI-generated coloring page suggestions.
"""
from django.db import models
from django.utils.translation import gettext_lazy as _

from .base import TimeStampedModel


class Suggestion(TimeStampedModel):
    """
    A coloring page idea generated by GPT, awaiting admin review.
    """
    STATUS_PENDING = "pending"
    STATUS_APPROVED = "approved"
    STATUS_DISMISSED = "dismissed"
    STATUS_CHOICES = [
        (STATUS_PENDING, _("Pending")),
        (STATUS_APPROVED, _("Approved")),
        (STATUS_DISMISSED, _("Dismissed")),
    ]

    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default=STATUS_PENDING,
        db_index=True,
    )
    image_prompt = models.TextField(verbose_name=_("Image prompt"))
    title_en = models.CharField(max_length=200, verbose_name=_("Title (EN)"))
    title_de = models.CharField(max_length=200, verbose_name=_("Title (DE)"))
    description_en = models.TextField(verbose_name=_("Description (EN)"))
    description_de = models.TextField(verbose_name=_("Description (DE)"))
    reasoning = models.TextField(blank=True, default="", verbose_name=_("Reasoning"))

    # Link to the generated page (set when approved and image created)
    coloring_page = models.ForeignKey(
        "coloring_pages.ColoringPage",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="suggestions",
    )

    class Meta:
        ordering = ["-created_at"]
        verbose_name = _("Suggestion")
        verbose_name_plural = _("Suggestions")

    def __str__(self):
        return f"[{self.status}] {self.title_en}"
